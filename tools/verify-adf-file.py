"""Independently extract a classic OFS/FFS DD file and verify every source byte.

No filesystem creator library is used. This is a bounded verifier for the ordinary
DOS0/DOS1 disks generated by this project, not a general Amiga filesystem driver.
"""
import argparse
import json
import struct
from pathlib import Path

class Disk:
    def __init__(self,data):
        if len(data)!=901120 or data[:3]!=b'DOS' or data[3] not in (0,1):
            raise ValueError('Expected standard DD DOS0/OFS or DOS1/FFS image')
        self.data=data;self.ffs=bool(data[3]);self.blocks=len(data)//512;self.root=self.blocks//2
        root=self.header(self.root,2,1)
        if root[3]!=72:raise ValueError('Unexpected root hash table size')

    def block(self,index):
        if not 2<=index<self.blocks:raise ValueError('Block pointer outside filesystem')
        return self.data[index*512:(index+1)*512]

    def header(self,index,kind,secondary):
        words=struct.unpack('>128I',self.block(index))
        if words[0]!=kind or words[127]!=(secondary&0xffffffff):raise ValueError('Unexpected header type')
        if sum(words)&0xffffffff:raise ValueError('Invalid block checksum')
        return words

    def name(self,index):
        block=self.block(index);size=block[432]
        if size>30:raise ValueError('Invalid classic filename length')
        return block[433:433+size].decode('latin1')

    def entry(self,path):
        parts=path.split('/')
        if not parts or any(not p or p in ('.','..') for p in parts):raise ValueError('Expected relative filesystem path')
        directory=self.root
        for depth,part in enumerate(parts):
            parent=self.header(directory,2,1 if directory==self.root else 2)
            found=None;visited=set()
            for pointer in parent[6:78]:
                while pointer:
                    if pointer in visited:raise ValueError('Directory chain cycle or duplicate')
                    visited.add(pointer);block=self.block(pointer);words=struct.unpack('>128I',block)
                    if words[0]!=2 or sum(words)&0xffffffff or words[125]!=directory:raise ValueError('Invalid directory entry')
                    if self.name(pointer).lower()==part.lower():
                        if found is not None:raise ValueError('Duplicate filename')
                        found=pointer
                    pointer=words[124]
            if found is None:raise ValueError('File not found: '+part)
            if depth+1<len(parts):self.header(found,2,2);directory=found
            else:return found
        raise ValueError('Missing filename')

    def pointers(self,index):
        result=[];pointer=index;visited=set();first=True
        while pointer:
            if pointer in visited:raise ValueError('Extension chain cycle')
            visited.add(pointer);table=self.header(pointer,2 if first else 16,-3)
            if table[1]!=pointer or table[2]>72:raise ValueError('Invalid file pointer table')
            result.extend(reversed(table[78-table[2]:78]));pointer=table[126];first=False
        if len(result)!=len(set(result)):raise ValueError('Duplicate file data pointer')
        return result

    def extract(self,path):
        index=self.entry(path);header=self.header(index,2,-3);size=header[81]
        if size>len(self.data):raise ValueError('Declared file exceeds disk capacity')
        chunks=[];seen=set();remaining=size;block_order=[]
        if not self.ffs:
            pointer=header[4];sequence=1
            while pointer:
                if pointer in seen:raise ValueError('Data chain cycle')
                seen.add(pointer);block_order.append(pointer);block=self.block(pointer);words=struct.unpack('>128I',block)
                if words[0]!=8 or words[1]!=index or words[2]!=sequence or sum(words)&0xffffffff:raise ValueError('Invalid OFS data block')
                count=words[3]
                if not 0<count<=488 or count>remaining:raise ValueError('Invalid OFS data size')
                chunks.append(block[24:24+count]);remaining-=count;pointer=words[4];sequence+=1
        else:
            pointer=index;extensions=set();first=True
            while pointer:
                if pointer in extensions:raise ValueError('Extension chain cycle')
                extensions.add(pointer);table=self.header(pointer,2 if first else 16,-3)
                if table[1]!=pointer or table[2]>72:raise ValueError('Invalid FFS pointer table')
                for block_pointer in reversed(table[78-table[2]:78]):
                    if not remaining or block_pointer in seen:raise ValueError('Unexpected duplicate/excess data block')
                    seen.add(block_pointer);block=self.block(block_pointer);count=min(512,remaining)
                    chunks.append(block[:count]);remaining-=count
                pointer=table[126];first=False
        if not self.ffs and block_order!=self.pointers(index):raise ValueError('OFS table and linked chain disagree')
        if remaining:raise ValueError('Truncated file chain')
        result=b''.join(chunks)
        if len(result)!=size:raise ValueError('File size mismatch')
        return result

def verify(image,path,expected):
    disk=Disk(image);actual=disk.extract(path)
    if actual!=expected:raise ValueError('Recovered file differs from source executable')
    return {'result':'PASS','filesystem':'FFS' if disk.ffs else 'OFS','disk_bytes':len(image),'file_bytes':len(actual),'byte_identical':True}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--adf',type=Path,required=True);parser.add_argument('--file',required=True);parser.add_argument('--source',type=Path,required=True)
    args=parser.parse_args();print(json.dumps(verify(args.adf.read_bytes(),args.file,args.source.read_bytes()),indent=2))
if __name__=='__main__':main()
